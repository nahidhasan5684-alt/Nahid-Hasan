@Composable
fun ReportingDashboardScreen(
    viewModel: ScornerViewModel,
    students: List<StudentEntity>,
    analytics: AnalyticsData,
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current
    var selectedFilter by remember { mutableStateOf("All Classes") }
    val filters = listOf("All Classes", "Class 12", "Class 11", "High Performers (5.00)")

    val filteredStudents = remember(students, selectedFilter) {
        when (selectedFilter) {
            "Class 12" -> students.filter { it.className.contains("12") }
            "Class 11" -> students.filter { it.className.contains("11") }
            "High Performers (5.00)" -> students.filter { it.currentGpa >= 4.90 }
            else -> students
        }
    }

    LazyColumn(
        modifier = modifier
            .fillMaxSize()
            .padding(horizontal = 16.dp),
        contentPadding = PaddingValues(vertical = 16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        // Admin Master Analytics Header
        item {
            Card(
                shape = RoundedCornerShape(20.dp),
                colors = CardDefaults.cardColors(containerColor = PrimaryBlue),
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(modifier = Modifier.padding(20.dp)) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Column {
                            Text(
                                text = "INSTITUTIONAL PERFORMANCE CONSOLE",
                                style = MaterialTheme.typography.labelSmall,
                                fontWeight = FontWeight.Bold,
                                color = Color.White.copy(alpha = 0.8f)
                            )
                            Text(
                                text = "SCORNER Executive Analytics",
                                style = MaterialTheme.typography.titleLarge,
                                fontWeight = FontWeight.Black,
                                color = Color.White
                            )
                        }

                        IconButton(
                            onClick = {
                                val report = "SCORNER Institutional Progress Report:\nTotal Students: ${students.size}\nAverage Institution GPA: 4.92\nAttendance Compliance: 96%\nReport generated by: ${AuthManager.currentUser.name}"
                                val intent = Intent(Intent.ACTION_SEND).apply {
                                    type = "text/plain"
                                    putExtra(Intent.EXTRA_TEXT, report)
                                }
                                context.startActivity(Intent.createChooser(intent, "Export Report"))
                            }
                        ) {
                            Icon(Icons.Filled.Share, contentDescription = "Export Report", tint = Color.White)
                        }
                    }

                    Spacer(modifier = Modifier.height(16.dp))

                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(8.dp)
                    ) {
                        AdminStatPill("Enrolled", "${students.size}", PrimaryLight, Modifier.weight(1f))
                        AdminStatPill("Mean GPA", "4.92", GoldYellow, Modifier.weight(1f))
                        AdminStatPill("Fee Cleared", "88%", SuccessGreen, Modifier.weight(1f))
                        AdminStatPill("Retention", "98.5%", SecondaryTeal, Modifier.weight(1f))
                    }
                }
            }
        }

        // Team & Student Productivity Radar
        item {
            ProductivityRadialGauge(
                productivityRate = analytics.productivityRate,
                attendanceRate = 96,
                modifier = Modifier.fillMaxWidth()
            )
        }

        // Filters Bar
        item {
            Text(
                text = "Cohort Progress & Rosters",
                style = MaterialTheme.typography.titleMedium,
                fontWeight = FontWeight.Bold
            )
            Spacer(modifier = Modifier.height(6.dp))
            LazyRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                items(filters) { filter ->
                    FilterChip(
                        selected = selectedFilter == filter,
                        onClick = { selectedFilter = filter },
                        label = { Text(filter) }
                    )
                }
            }
        }

        // Student Progress Roster Table
        items(filteredStudents) { student ->
            StudentRosterCard(
                student = student,
                isSelected = student.id == viewModel.selectedStudentId.collectAsState().value,
                onSelect = { viewModel.selectStudent(student.id) }
            )
        }

        // Administrator Actions
        item {
            Card(
                shape = RoundedCornerShape(16.dp),
                colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(modifier = Modifier.padding(16.dp)) {
                    Text(
                        text = "Administrative Actions",
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.Bold
                    )
                    Spacer(modifier = Modifier.height(8.dp))

                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(8.dp)
                    ) {
                        OutlinedButton(
                            onClick = { viewModel.showAddStudentDialog.value = true },
                            modifier = Modifier.weight(1f)
                        ) {
                            Icon(Icons.Filled.PersonAdd, contentDescription = null, modifier = Modifier.size(16.dp))
                            Spacer(modifier = Modifier.width(6.dp))
                            Text("Add Student")
                        }

                        Button(
                            onClick = {
                                viewModel.broadcastAnnouncement(
                                    "Midterm Examination Notice",
                                    "All faculty and students are notified that Midterm transcripts are verified."
                                )
                            },
                            modifier = Modifier.weight(1f)
                        ) {
                            Icon(Icons.Filled.Campaign, contentDescription = null, modifier = Modifier.size(16.dp))
                            Spacer(modifier = Modifier.width(6.dp))
                            Text("Broadcast")
                        }
                    }
                }
            }
        }
    }
}

@Composable
fun AdminStatPill(
    label: String,
    value: String,
    accentColor: Color,
    modifier: Modifier = Modifier
) {
    Surface(
        shape = RoundedCornerShape(10.dp),
        color = Color.White.copy(alpha = 0.15f),
        modifier = modifier
    ) {
        Column(
            modifier = Modifier.padding(8.dp),
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            Text(value, fontWeight = FontWeight.Black, fontSize = 16.sp, color = accentColor)
            Text(label, fontSize = 10.sp, color = Color.White.copy(alpha = 0.8f))
        }
    }
}

@Composable
fun StudentRosterCard(
    student: StudentEntity,
    isSelected: Boolean,
    onSelect: () -> Unit
) {
    Card(
        shape = RoundedCornerShape(14.dp),
        colors = CardDefaults.cardColors(
            containerColor = if (isSelected) MaterialTheme.colorScheme.primaryContainer else MaterialTheme.colorScheme.surface
        ),
        modifier = Modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(14.dp))
            .clickable { onSelect() }
            .testTag("student_roster_${student.id}")
    ) {
        Row(
            modifier = Modifier.padding(14.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Box(
                modifier = Modifier
                    .size(44.dp)
                    .clip(CircleShape)
                    .background(PrimaryBlue.copy(alpha = 0.15f)),
                contentAlignment = Alignment.Center
            ) {
                Text(
                    text = student.name.take(2).uppercase(),
                    fontWeight = FontWeight.Bold,
                    color = PrimaryBlue
                )
            }

            Spacer(modifier = Modifier.width(12.dp))

            Column(modifier = Modifier.weight(1f)) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Text(
                        text = student.name,
                        fontWeight = FontWeight.Bold,
                        style = MaterialTheme.typography.bodyMedium
                    )
                    if (isSelected) {
                        Spacer(modifier = Modifier.width(6.dp))
                        Text("(Active)", color = PrimaryBlue, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                    }
                }
                Text(
                    text = "${student.className} • ${student.college}",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
                Text(
                    text = "SSC: ${student.sscGpa} | Current GPA: ${student.currentGpa} | Att: ${student.attendanceRate}%",
                    style = MaterialTheme.typography.labelSmall,
                    color = PrimaryBlue,
                    fontWeight = FontWeight.SemiBold
                )
            }

            Surface(
                shape = RoundedCornerShape(8.dp),
                color = if (student.currentGpa >= 4.90) SuccessGreen else PrimaryLight
            ) {
                Text(
                    text = "${student.currentGpa}",
                    color = Color.White,
                    fontWeight = FontWeight.Bold,
                    fontSize = 12.sp,
                    modifier = Modifier.padding(horizontal = 8.dp, vertical = 4.dp)
                )
            }
        }
    }
}
